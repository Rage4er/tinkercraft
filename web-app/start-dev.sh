#!/usr/bin/env bash
# --------------------------------------------------------------
#  Запуск dev‑сервера Vite для TinkerCraft Web
#  Требуется: Node.js (≥18) и pnpm (≥8) установлены глобально
# --------------------------------------------------------------

set -euo pipefail   # надёжный режим: прекращаем скрипт при любой ошибке

# --------------------------------------------------------------
#  Перейти в директорию скрипта (чтобы можно было запускать его
#  из любого места)
# --------------------------------------------------------------
cd "$(dirname "${BASH_SOURCE[0]}")"

# --------------------------------------------------------------
#  Проверка наличия pnpm
# --------------------------------------------------------------
if ! command -v pnpm >/dev/null 2>&1; then
    echo "[ОШИБКА] pnpm не найден в PATH."
    echo "Установите pnpm:  npm i -g pnpm"
    exit 1
fi

# --------------------------------------------------------------
#  Установка зависимостей (если ещё не установлены)
# --------------------------------------------------------------
if [[ ! -d node_modules ]]; then
    echo "[ИНФО] Устанавливаю зависимости через pnpm…"
    pnpm install --frozen-lockfile
else
    echo "[ИНФО] Папка node_modules уже существует – пропускаю установку."
fi

# --------------------------------------------------------------
#  Запуск Vite dev server
# --------------------------------------------------------------
echo "[ИНФО] Запускаю Vite dev server…"
pnpm dev

# Если сервер завершился с ошибкой – держим терминал открытым,
# чтобы пользователь мог увидеть вывод (полезно при запуске
# двойным щелчком в графическом окружении).
if [[ $? -ne 0 ]]; then
    echo
    echo "[ОШИБКА] Vite dev server завершился с кодом $?."
    read -p "Нажмите Enter, чтобы закрыть окно..."
fi
